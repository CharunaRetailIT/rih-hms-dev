        [Authorize(Roles = "Reports")]
        public ActionResult RPTGRNSummary(GRNSummaryViewModel vvm)
        {
            if (_bllconfiguration.GetConfiguration("UReports", Convert.ToInt32(Session["loggedusercompanyId"].ToString())).ConfigurationOn)
            {

                if (!_appmanager.CheckReportPermissions(999, Session["loggeduserempcode"].ToString(), "RPTGRNSummary"))
                {
                    @ViewBag.Permissions = "No user permissions to View GRN Summary";
                    return View("~/Views/Account/AccessDenied.cshtml");
                }

            }
            var grn = _bllgrn.GetGRNSummaryReport(vvm.LocationId, 
                vvm.DocumentId, 
                vvm.DateFrom, 
                vvm.DateTo, 
                vvm.SupplierId,
                Convert.ToInt32(Session["loggedusercompanyId"].ToString())).Where(g=>g.DocumentID==4);
            List<GRNSummaryViewModel> grnsummarymodel = new List<GRNSummaryViewModel>();
            foreach (var s in grn)
            {
                GRNSummaryViewModel v = new GRNSummaryViewModel();
                v.PurchaseHeaderId = s.PurchaseHeaderId;
                v.DocumentNo = s.DocumentNo;
                if (s.GRNLocationId != 0)
                {
                    v.Location = _blllocation.GetLocationById(s.GRNLocationId).LocationName;
                }
                else
                {
                    v.Location = "All";
                }
                v.GRNDate = s.GRNDate;
                var status = _blldocstatus.GetDocStatusById(s.DocumentStatus);
                if(status!=null)
                v.Status =status.Description;
                v.NetAmount = s.NetAmount;
                v.GrossAmount = s.GrossAmount;
                grnsummarymodel.Add(v);
            }
            ViewBag.poLocationId = vvm.LocationId;
            ViewBag.poSupplierId = vvm.SupplierId;
            return View("~/Views/Reports/GRN/RPTGRNSummary.cshtml", grnsummarymodel);
        }

