            if (_bllusermaster.GetUserPermissionsByEmpNo(Session["loggeduserempcode"].ToString()).Select(p => p.FunctionName).Contains("EditGRNCost"))
            {
                ViewBag.EditCostPriceOnGRN = "1";
            }
            else
            {
                ViewBag.EditCostPriceOnGRN = "0";
            }
            ViewBag.supplierId = grnheader.SupplierID;
            ViewBag.CurrencyId = grnheader.CurrencyID;
            ViewBag.PaymentTermId = grnheader.PaymentTermID;
            ViewBag.paymentMethodsId = grnheader.PaymentMethodId;
            ViewBag.locationId = grnheader.GRNLocationId;
            ViewBag.EventId = grnheader.EventId;
            
            if (grnheader.GRNDetail.Count == 0)
            {
                @ViewBag.Message = "2";
                return View("~/Views/Transactions/GRN/EditGRN.cshtml", grnheader);
            }

            var id = RouteData.Values["id"] + Request.Url.Query;
            grnheader.PurchaseHeaderId = Convert.ToInt64(grnheader.PurchaseHeaderId);
            grnheader.ModifiedDate = DateTime.Now;
            grnheader.ModifiedUser = Session["loggeduser"].ToString();

            if (Convert.ToBoolean(Session["APPGRN"]) == true) // Approval config ON
            {
                // Pending Approvals
                grnheader.DocumentStatus = 2;
                grnheader.IsGRN = false;
                grnheader.IsTempGRN = false;
            }
            else
            {
                // Aproved
                grnheader.DocumentStatus = 3;
                grnheader.IsGRN = true;
                grnheader.IsTempGRN = false;
            }

            if (ModelState.IsValid == false)
            {
                @ViewBag.Message = "2";
                return View("~/Views/Transactions/GRN/EditGRN.cshtml", grnheader);
            }

            int docid = _bllcommon.GetDcumentId("GRN", Convert.ToInt32(Session["loggedusercompanyId"].ToString()));
            var docnum = _bllcommon.GetDocumentNo("GRN",
                                                    Convert.ToInt32(Session["loggeduserlocId"]),
                                                    Convert.ToString(grnheader.GRNLocationId),
                                                     docid,
                                                     false, Convert.ToInt32(Session["loggedusercompanyId"].ToString()));


            if (@ViewBag.BackDateGRN == false)
            {
                grnheader.GRNDate = DateTime.Now;
            }
            grnheader.DocumentID = docid;
            grnheader.DocumentNo = docnum;
            grnheader.CostCentreID = Convert.ToInt32(grnheader.GRNLocationId);
            grnheader.DocumentDate = DateTime.Now;
            grnheader.BatchNo = "0";
            grnheader.CompanyID = Convert.ToInt32(Session["loggedusercompanyId"].ToString());
            @ViewBag.GRNCode = grnheader.DocumentNo;
            grnheader.IsTOGTransfer = false;

            if (grnheader.POID != 0)
            {
                List<PurchaseOrderDetail> Qtys = _bllpurchaseorder.GetPOIdByQtys(grnheader.POID);

                // Make sure both lists have the same count
                if (grnheader.GRNDetail.Count != Qtys.Count)
                {
                    // Handle the case where counts do not match
                    // You may throw an exception, log a warning, or handle it according to your requirements
                }

                for (int i = 0; i < grnheader.GRNDetail.Count; i++)
                {
                    // Match each item from poheader.PODetail with corresponding item from Qtys
                    grnheader.GRNDetail[i].GRNQuantity = Qtys[i].OrderQty;
                    grnheader.GRNDetail[i].OrderQty = Qtys[i].OrderQty;
                }
            }

            if (_bllgrn.UpdateGRN(grnheader))
            {
                @ViewBag.Message = "1";


                grnheader.Company = _bllcompany.GetCompanyById(grnheader.CompanyID).CompanyName;
                grnheader.Location = _blllocation.GetLocationById(grnheader.GRNLocationId).LocationName;
                grnheader.GRNDetail.ToList().ForEach(d =>
                {
                    var prd = _bllproduct.GetProductById(d.ProductID);
                    d.ProductName = prd.ProductName;
                    d.ProductCode = prd.ProductCode;
                });


                ViewBag.PurchaseHeaderId = grnheader.PurchaseHeaderId;
                return View("~/Views/Transactions/GRN/EditGRN.cshtml", grnheader);

            }
            else
            {
                @ViewBag.Message = "2";
                return View("~/Views/Transactions/GRN/EditGRN.cshtml", grnheader);
            }

        }


