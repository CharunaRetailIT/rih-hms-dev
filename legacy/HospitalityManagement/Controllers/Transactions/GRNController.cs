        public JsonResult GetDataTest(long id, long supplierid, string grntype)
        {

            var po = __bllpo.GetPODetById(id).ToList().Where(p => p.GRNQuantity != p.OrderQty);
            po.ToList().ForEach
           (
               r =>
               {
                   r.ProductName = _bllproduct.GetProductById(r.ProductId).ProductName;

               }
           );
            bool istaxinclusive = _bllcommon.GetConfigurations().IsTaxInclusiveToCost;
            string suppliertaxnumber = _bllsupplier.GetSupplierById(supplierid).TaxRegistrationNo;
            int x = po.Count();
            List<GRNTaxViewModel> vvm = new List<GRNTaxViewModel>();
            foreach (var poitem in po)
            {
                GRNTaxViewModel vm = new GRNTaxViewModel();
                var taxproducts = _blltax.GetProductTaxByProductId(poitem.ProductId);

                vm.ProductId = poitem.ProductId;
                vm.CostPrice = poitem.CostPrice;
                vm.SellingPrice = poitem.SellingPrice;
                vm.POQuantity = poitem.OrderQty;

                //vm.Qty = poitem.OrderQty;
                vm.Qty = poitem.OrderQty - poitem.GRNQuantity;
                vm.FreeQty = poitem.FreeQty;
                //vm.CostValue = poitem.CostPrice * poitem.OrderQty;
                vm.TaxPrc = 0;
                vm.TaxAmount = 0;
                vm.ItemDesc = poitem.StockCode + " - " + poitem.ProductName;
                // vm.UOM = vm.Qty + _bllproduct.GetUOMById(_bllproduct.GetProductById(vm.ProductId).PurchasingUnit);
                vm.UOM =  _bllproduct.GetUOMById(_bllproduct.GetProductById(vm.ProductId).PurchasingUnit);
                foreach (var tx in taxproducts)
                {
                    if (!string.IsNullOrEmpty(suppliertaxnumber))
                    {

                        if (tx.ProductId == poitem.ProductId)
                        {
                            vm.TaxPrc += tx.TaxPrc;
                            // vm.TaxAmount += ((vm.CostPrice * tx.TaxPrc / 100)*vm.Qty);
                            vm.TaxAmount += (vm.CostPrice * tx.TaxPrc / 100);
                            if (istaxinclusive)
                            {
                                vm.CostPrice = vm.CostPrice - vm.TaxAmount;
                            }
                            else
                            {
                                vm.CostPrice = vm.CostPrice + vm.TaxAmount;
                            }
                        }
                        else
                        {
                            vm.TaxPrc = 0;
                            vm.TaxAmount = 0;
                        }
                    }
                    else
                    {
                        vm.TaxPrc = 0;
                        vm.TaxAmount = 0;
                    }

                    vm.IsExpiry = _bllproduct.GetProductById(poitem.ProductId).IsExpiry;
                }

                vm.CostPrice = poitem.CostPrice;
                vm.Discounts = poitem.Discounts;
                vm.CostValue = Math.Round(poitem.CostPrice * poitem.OrderQty, 3);
                if (grntype == "Manual")
                {
                    vm.TaxAmount = vm.TaxAmount * poitem.OrderQty;
                }
                else if (grntype == "POBased")
                {
                    vm.TaxAmount = poitem.ItemTaxTotal;
                }

                var poheader = _bllpurchaseorder.GetPOById(po.First().PurchaseOrderHeaderId);
                vm.CurrencyId = poheader.CurrencyId;
                vm.CurrencyRate = poheader.CurrencyRate;
                vm.PaymentMethodId = poheader.PaymentMethodId;
                vm.PaymentTermId = poheader.PaymentTermId;
                vm.LocationId = Convert.ToInt32(poheader.POLocationId);
                vm.TotalTaxAmount = poheader.TotalTaxAmount;
                
                vvm.Add(vm);


                //vm.Discounts = poitem.Discounts;
                //vvm.Add(vm);
            }
            // var podetail = po.First();
            return new JsonResult { Data = vvm, JsonRequestBehavior = JsonRequestBehavior.AllowGet };
        }


