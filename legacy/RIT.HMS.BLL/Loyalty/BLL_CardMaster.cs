        private string CreateSQL(int cardmastertype,string fm,DateTime fd,string sm,DateTime sd,int locid,int compid)
        {
            string q = "INSERT INTO [SMS].[dbo].[TBLM_MessegeHead]([MessegeID],[MsgParam],[Recever],[Status],[CreateDate],[LocationId]) VALUES";

            var recivers = (from lc in _unitofwork.LoyaltyCustomerReporsitory.Get()
                           join c in _unitofwork.CustomerRepository.Get() on lc.CustomerId equals c.CustomerID
                           where lc.CardMasterId == cardmastertype && c.LocationId == locid && c.CompanyID == compid
                           select new
                           {
                               MobileNo = c.Mobile                     
                           }
                        ).ToList();
            if (!string.IsNullOrEmpty(fm))
            {
                foreach (var r in recivers)
                {
                    q += "(1,'#" + fm + "'," + r.MobileNo + ",'0','" + DateTime.Now.ToString("yyyy-MM-dd") + "'," + locid + "),";
                }
            }
            if (!string.IsNullOrEmpty(sm))
            {
                foreach (var r in recivers)
                {
                    q += "(1,'#" + sm + "'," + r.MobileNo + ",'0','" + DateTime.Now.ToString("yyyy-MM-dd") + "'," + locid + "),";
                }
            }
            return q.Remove(q.Length - 1, 1);
        }
