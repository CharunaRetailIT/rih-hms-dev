        public string GetNewCode(string formName)
        {
            AutoGenerateInfo autoGenerateInfo;
            autoGenerateInfo = _unitofwork.AutoGeneratedInfoRepository.Get(a=>a.FormName==formName).FirstOrDefault();
            string getNewCode = string.Empty;
            string preFix = autoGenerateInfo.Prefix;
            int codeLength = autoGenerateInfo.CodeLength;

            getNewCode = _unitofwork.CardMasterRepository.Get().Max(c => c.CardCode);
            if (getNewCode != null)
                getNewCode = getNewCode.Trim().Substring(preFix.Length, codeLength - preFix.Length);
            else
                getNewCode = "0";

            getNewCode = (int.Parse(getNewCode) + 1).ToString();
            getNewCode = preFix + new StringBuilder().Insert(0, "0", (codeLength - (preFix.Length + getNewCode.Length))) + getNewCode;
            return getNewCode;
        }

        public bool SaveCardMaster(CardMaster cardmaster)
        {
            try
            {
                _unitofwork.CreateTransaction();
                foreach (var s in cardmaster.LoyaltyCardSchems)
                {
                    s.LocationId = cardmaster.LocationId;
                    s.CreatedUser = cardmaster.CreatedUser;
                    s.CompanyID = cardmaster.CompanyID;
                }
                if (cardmaster.IsExists == false)
                {                    
                    _unitofwork.CardMasterRepository.Insert(cardmaster);
                    _unitofwork.Save();
                }
                else
                {
                    var existsheader = _unitofwork.CardMasterRepository.GetById(cardmaster.CardMasterId);
                    _unitofwork.CardMasterRepository.UpdateBySet(existsheader,cardmaster);
                    _unitofwork.LoyaltyCardSchemsRepository.DeleteRange(existsheader.LoyaltyCardSchems);
                    List<LoyaltyCardSchems> l2 = new List<LoyaltyCardSchems>();
                    foreach (var l in cardmaster.LoyaltyCardSchems)
                    {
                        LoyaltyCardSchems l1 = new LoyaltyCardSchems();
                        l1.CardMasterId = cardmaster.CardMasterId;
                        l1.BillFromValue = l.BillFromValue;
                        l1.BillToValue = l.BillToValue;
                        l1.Increment = l.Increment;
                        l1.PointValue = l.PointValue;
                        l1.PointPer = l.PointPer;
