        public CustomerStatementViewModel CustomerStatement(int customerid)
        {

            CustomerStatementViewModel statement = new CustomerStatementViewModel();
            statement.CustomerId = customerid;
            List<CustomerStatementViewModel.PointsDetail> details = new List<CustomerStatementViewModel.PointsDetail>();
            List<InvLoyaltyTransaction> loyaltytransactions = new List<InvLoyaltyTransaction>();
            if (customerid != 0)
            {
                loyaltytransactions = _unitofwork.InvLoyaltyTransactionReporsitory.Get(t => t.CustomerID == customerid).ToList();
            }
            else
            {
                loyaltytransactions = _unitofwork.InvLoyaltyTransactionReporsitory.Get().ToList();
            }

            foreach (var s in loyaltytransactions)
            {
                CustomerStatementViewModel.PointsDetail detail = new CustomerStatementViewModel.PointsDetail();
                detail.CustomerName = _unitofwork.CustomerRepository.GetById(s.CustomerID).CustomerName;
                detail.Recipt = s.Receipt;
                detail.Amount = s.Amount;
                detail.Points = s.Points;
                detail.CardNumber = s.CardNo;
                details.Add(detail);
            }
            statement.Detail = details;
            return statement;
        }

