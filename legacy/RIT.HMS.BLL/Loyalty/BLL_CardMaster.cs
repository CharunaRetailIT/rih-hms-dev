                        l1.CreatedUser = l1.CreatedUser;
                        l1.ModifiedDate = l1.ModifiedDate;
                        l1.ModifiedUser = l1.ModifiedUser;
                        l1.DataTransfer = l.DataTransfer;
                        l2.Add(l1);
                    }
                    _unitofwork.LoyaltyCardSchemsRepository.BulkInsert(l2);
                    _unitofwork.Save();
